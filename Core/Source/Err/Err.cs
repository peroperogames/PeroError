using System;
using System.Collections.Generic;
using System.Runtime.CompilerServices;
using System.Text;

namespace PeroTools2.Error;

/// <summary>Error factory</summary>
public static class Err
{
    /// <summary>
    /// Creates an <see cref="Err{TKind}"/> instance.<br/>
    /// When the error enum has companion classes, the companion class constructor should be called
    /// instead of this method
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    /// <remarks>
    /// This method should be used to create a new error directly.
    /// To wrap the creation of an Err, use the <see cref="Err{TKind}"/> constructor instead and pass the
    /// correct <see cref="CallerInfo"/>, so that the caller info stays accurate.
    /// </remarks>
    public static Err<TKind> New<TKind>(
        TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null,
        [CallerFilePath]
        string callerFilePath = null,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        new(
            kind, message, null, null,
            new CallerInfo(callerMemberName, callerFilePath, callerLineNumber)
        );

    /// <summary>
    /// Wraps an underlying error into a new error.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="causedBy">Underlying error being wrapped</param>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    public static Err<TKind> Warp<TKind>(
        this ErrBase causedBy, TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null,
        [CallerFilePath]
        string callerFilePath = null,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        new(
            kind, message, causedBy, null,
            new CallerInfo(callerMemberName, callerFilePath, callerLineNumber)
        );

    /// <summary>
    /// Wraps an underlying error into a new error, but still uses the old ErrKind and Message.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="causedBy">Underlying error being wrapped</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    public static Err<TKind> Warp<TKind>(
        this Err<TKind> causedBy,
        [CallerMemberName]
        string callerMemberName = null,
        [CallerFilePath]
        string callerFilePath = null,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum
    {
        causedBy.AddStackTrace(new CallerInfo(callerMemberName, callerFilePath, callerLineNumber));
        return causedBy;
    }

    // Companion classes are generated automatically by PeroTools2.PeroError.Generator;
    // just use [ErrMsg] / [ErrArg] on the error enum fields, see ErrMsgAttribute / ErrArgAttribute

    /// <summary>
    /// Wraps an Exception into a new error.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="ex">Underlying exception being wrapped</param>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    public static Err<TKind> Warp<TKind>(
        this Exception ex, TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null,
        [CallerFilePath]
        string callerFilePath = null,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        new(
            kind, message, null, ex,
            new CallerInfo(callerMemberName, callerFilePath, callerLineNumber)
        );
}

/// <summary>Error object that carries an error enum</summary>
/// <typeparam name="TKind">Error enum type</typeparam>
public class Err<TKind> : ErrBase where TKind : struct, Enum
{
    /// <summary>Error enum value of the current error</summary>
    public virtual TKind kind { get; }

    /// <inheritdoc cref="ErrBase.causedBy"/>
    public override ErrBase causedBy { get; }

    /// <inheritdoc cref="ErrBase.message"/>
    public override string message { get; }

    /// <inheritdoc cref="ErrBase.exception"/>
    public override Exception exception { get; }

    private Lazy<IList<string>> notes { get; } = new(static () => new List<string>(5));

    /// <summary>Simulates a stack trace with CallerInfo</summary>
    protected readonly List<CallerInfo> stackTrace;

    /// <summary>
    /// Should not be used directly.<br/>
    /// When creating a new error, use <see cref="Err.New{TKind}"/> instead
    /// </summary>
    protected internal Err(TKind kind, string message, ErrBase causedBy, Exception exception, CallerInfo callerInfo)
    {
        this.kind = kind;
        this.message = message;
        this.causedBy = causedBy;
        this.exception = exception;
        stackTrace = [callerInfo];
    }

    /// <summary>Appends one frame of stack trace info</summary>
    protected internal void AddStackTrace(CallerInfo callerInfo)
    {
        stackTrace.Add(callerInfo);
    }

    /// <summary>
    /// Convenience conversion of this <see cref="Err{TKind}"/> to the companion class of the
    /// error enum (if any)
    /// </summary>
    public TErr CastTo<TErr>() where TErr : Err<TKind> => (TErr)this;

    /// <inheritdoc cref="ErrBase.Panic"/>
    public override Exception Panic() => new ManualPanicException(ToString()); // Direct throw loses the stack trace

    /// <inheritdoc cref="ErrBase.CausedByException"/>
    public override bool CausedByException(out Exception? ex)
    {
        ErrBase current = this;
        while (current != null)
        {
            if (current.exception != null)
            {
                ex = current.exception;
                return true;
            }
            current = current.causedBy;
        }
        ex = null;
        return false;
    }

    /// <inheritdoc cref="ErrBase.AddNote"/>
    protected internal override void AddNote(string note) => notes.Value.Add(note);

    /// <inheritdoc cref="ErrBase.WriteToStringBuilder"/>
    protected internal override void WriteToStringBuilder(StringBuilder sb)
    {
        // Could be replaced with PeroString concatenation later
        sb.AppendFormat("{0}.{1}\n", typeof(TKind).FullName, kind);
        for (int i = stackTrace.Count - 1; i >= 0; i--)
        {
            var callerInfo = stackTrace[i];
            sb.AppendFormat("  At: {0} @ {1}:{2}\n", callerInfo.callerMemberName, callerInfo.callerFilePath, callerInfo.callerLineNumber.ToString());
        }
        sb.AppendFormat("  Message: {0}\n", message);
        // Notes
        if (notes.IsValueCreated)
        {
            sb.AppendLine("  Notes:");
            for (int i = 0; i < notes.Value.Count; i++)
            {
                sb.AppendFormat("    {0}: {1}\n", i.ToString(), notes.Value[i]);
            }
        }
        // Exception
        if (exception != null)
        {
            sb.AppendLine("  Exception:");
            sb.AppendLine("========== Exception Start ==========");
            sb.AppendLine(exception.ToString());
            // Possibly useful info inside the Exception (ToString() prints Message and StackTrace):
            // sb.AppendFormat("  ExMessage: {0}\n", exception.Message);
            // sb.AppendFormat("  TargetSite: {0}\n", exception.TargetSite);
            // sb.AppendFormat("  Source: {0}\n", exception.Source);
            // sb.AppendLine("  StackTrace:");
            // sb.AppendLine(exception.StackTrace);
            sb.AppendLine("========== Exception End ==========");
        }
        // CausedBy
        if (causedBy != null)
        {
            sb.AppendLine("========== CausedBy ==========");
            causedBy.WriteToStringBuilder(sb);
        }
    }

    /// <summary>Formats the complete error info (including stack trace/Notes/Exception/CausedBy)</summary>
    public override string ToString()
    {
        // Recursive ToString calls would allocate several StringBuilders, so passing one in saves allocations
        var sb = new StringBuilder();
        WriteToStringBuilder(sb);
        return sb.ToString();
    }
}