using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Runtime.CompilerServices;
using System.Text;

namespace PeroTools2.Error;

/// <summary>Error factory</summary>
public static class Err
{
    /// <summary>
    /// Creates an <see cref="Err{TKind}"/> instance.<br/>
    /// When the error enum has companion classes, the companion class constructor should be called
    /// instead of this method
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    /// <remarks>
    /// This method should be used to create a new error directly.
    /// To wrap the creation of an Err, use the <see cref="Err{TKind}"/> constructor instead and pass the
    /// correct <see cref="CallerInfo"/>, so that the caller info stays accurate.
    /// </remarks>
    public static Err<TKind> New<TKind>(
        TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null!,
        [CallerFilePath]
        string callerFilePath = null!,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        Err<TKind>.Rent(kind, message, null!, null!,
            new CallerInfo(callerMemberName!, callerFilePath!, callerLineNumber));

    /// <summary>
    /// Wraps an underlying error into a new error.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="causedBy">Underlying error being wrapped</param>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    public static Err<TKind> Wrap<TKind>(
        this ErrBase causedBy, TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null!,
        [CallerFilePath]
        string callerFilePath = null!,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        Err<TKind>.Rent(
            kind, message, causedBy, null!,
            new CallerInfo(callerMemberName!, callerFilePath!, callerLineNumber)
        );

    /// <summary>
    /// Appends a stack frame to an existing <see cref="Err{TKind}"/>.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="causedBy">The error to append the stack frame to</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    /// <remarks>
    /// Unlike the <c>Wrap</c> overloads, this one does <b>not</b> create a new error: it modifies
    /// <paramref name="causedBy"/> in place and returns the very same instance, keeping the original
    /// kind and message. Because the instance is mutated, the same error must not be marked from
    /// several threads at once.
    /// </remarks>
    public static Err<TKind> AddCallerFrame<TKind>(
        this Err<TKind> causedBy,
        [CallerMemberName]
        string callerMemberName = null!,
        [CallerFilePath]
        string callerFilePath = null!,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum
    {
        causedBy.AddStackTrace(new CallerInfo(callerMemberName!, callerFilePath!, callerLineNumber));
        return causedBy;
    }

    // Companion classes are generated automatically by PeroTools2.PeroError.Generator;
    // just use [ErrMsg] / [ErrArg] on the error enum fields, see ErrMsgAttribute / ErrArgAttribute

    /// <summary>
    /// Wraps an Exception into a new error.
    /// </summary>
    /// <typeparam name="TKind">Error enum type</typeparam>
    /// <param name="ex">Underlying exception being wrapped</param>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="callerMemberName">Do not fill in. Generated by the compiler</param>
    /// <param name="callerFilePath">Do not fill in. Generated by the compiler</param>
    /// <param name="callerLineNumber">Do not fill in. Generated by the compiler</param>
    public static Err<TKind> Wrap<TKind>(
        this Exception ex, TKind kind, string message,
        [CallerMemberName]
        string callerMemberName = null!,
        [CallerFilePath]
        string callerFilePath = null!,
        [CallerLineNumber]
        int callerLineNumber = 0
    ) where TKind : struct, Enum =>
        Err<TKind>.Rent(
            kind, message, null!, ex,
            new CallerInfo(callerMemberName!, callerFilePath!, callerLineNumber)
        );
}

/// <summary>Error object that carries an error enum</summary>
/// <typeparam name="TKind">Error enum type</typeparam>
public class Err<TKind> : ErrBase where TKind : struct, Enum
{
    /// <summary>Error enum value of the current error</summary>
    public virtual TKind kind { get; private set; }

    /// <inheritdoc/>
    public override ErrBase? causedBy => m_CausedBy;

    /// <inheritdoc/>
    public override string message => m_Message;

    /// <inheritdoc/>
    public override Exception? exception => m_Exception;

    private ErrBase? m_CausedBy;
    private string m_Message;
    private Exception? m_Exception;

    private Lazy<List<string>> notes { get; } = new(static () => new List<string>(5));

    private static readonly ConcurrentStack<Err<TKind>> s_Pool = new();

    internal static Err<TKind> Rent(TKind kind, string message, ErrBase causedBy, Exception exception, CallerInfo callerInfo)
    {
        if (s_Pool.TryPop(out var err))
        {
            err.Init(kind, message, causedBy, exception, callerInfo);
        }
        else
        {
            err = new Err<TKind>(kind, message, causedBy, exception, callerInfo);
        }
        return err;
    }

    internal static Err<TKind> Rent(TKind kind, string message, ErrBase causedBy, Exception exception, List<CallerInfo> stackTrace)
    {
        if (s_Pool.TryPop(out var err))
        {
            err.Init(kind, message, causedBy, exception, stackTrace);
        }
        else
        {
            err = new Err<TKind>(kind, message, causedBy, exception, stackTrace);
        }
        return err;
    }

    internal static void Return(Err<TKind> err)
    {
        err.Reset();
        err.OnReturn();
    }

    /// <summary>
    /// Called when the error goes back to the pool. A derived companion class overrides this to keep
    /// its own pool, so instances of different companion classes never get mixed up.
    /// </summary>
    protected virtual void OnReturn() => s_Pool.Push(this);

    /// <summary>Simulates a stack trace with CallerInfo</summary>
    protected readonly List<CallerInfo> stackTrace;

    /// <summary>
    /// Should not be used directly.<br/>
    /// When creating a new error, use <see cref="Err.New{TKind}"/> instead
    /// </summary>
    protected internal Err(TKind kind, string message, ErrBase causedBy, Exception exception, CallerInfo callerInfo)
    {
        this.kind = kind;
        m_Message = message;
        m_CausedBy = causedBy;
        m_Exception = exception;
        stackTrace = [callerInfo];
    }

    private Err(TKind kind, string message, ErrBase causedBy, Exception exception, List<CallerInfo> stackTrace)
    {
        this.kind = kind;
        m_Message = message;
        m_CausedBy = causedBy;
        m_Exception = exception;
        this.stackTrace = stackTrace;
    }

    /// <summary>Appends one frame of stack trace info</summary>
    protected internal void AddStackTrace(CallerInfo callerInfo) => stackTrace.Add(callerInfo);

    /// <summary>
    /// Convenience conversion of this <see cref="Err{TKind}"/> to the companion class of the
    /// error enum (if any)
    /// </summary>
    public TErr CastTo<TErr>() where TErr : Err<TKind> => (TErr)this;

    /// <summary>
    /// Converts to a new <see cref="Err{TTo}"/> with new kind and message, which keeps stored Error info (causedBy/exception/stackTrace).
    /// </summary>
    /// <param name="targetKind">New error kind.</param>
    /// <param name="newMessage">New message (using current message if null or empty).</param>
    /// <typeparam name="TTo">New error kind type.</typeparam>
    /// <returns>A new <see cref="Err{TTo}"/> with new kind and message, which keeps stored Error info (causedBy/exception/stackTrace).</returns>
    public Err<TTo> CastTo<TTo>(TTo targetKind, string newMessage = "") where TTo : struct, Enum => Err<TTo>.Rent(targetKind, string.IsNullOrEmpty(newMessage) ? message : newMessage, causedBy!, exception!, stackTrace);

    /// <inheritdoc cref="ErrBase.Panic"/>
    public override Exception Panic() => new ManualPanicException(ToString()); // Direct throw loses the stack trace

    /// <inheritdoc cref="ErrBase.CausedByException"/>
    public override bool CausedByException(out Exception? ex)
    {
        ErrBase current = this;
        while (current != null)
        {
            if (current.exception != null)
            {
                ex = current.exception;
                return true;
            }
            current = current.causedBy;
        }
        ex = null;
        return false;
    }

    /// <inheritdoc cref="ErrBase.AddNote"/>
    protected internal override void AddNote(string note) => notes.Value.Add(note);

    /// <inheritdoc cref="ErrBase.WriteToStringBuilder"/>
    protected internal override void WriteToStringBuilder(StringBuilder sb)
    {
        // Could be replaced with PeroString concatenation later
        sb.AppendFormat("{0}.{1}\n", typeof(TKind).FullName, kind);
        for (int i = stackTrace.Count - 1; i >= 0; i--)
        {
            var callerInfo = stackTrace[i];
            sb.AppendFormat("  At: {0} @ {1}:{2}\n", callerInfo.callerMemberName, callerInfo.callerFilePath, callerInfo.callerLineNumber.ToString());
        }
        sb.AppendFormat("  Message: {0}\n", message);
        // Notes
        if (notes.IsValueCreated)
        {
            sb.AppendLine("  Notes:");
            for (int i = 0; i < notes.Value.Count; i++)
            {
                sb.AppendFormat("    {0}: {1}\n", i.ToString(), notes.Value[i]);
            }
        }
        // Exception
        if (exception != null)
        {
            sb.AppendLine("  Exception:");
            sb.AppendLine("========== Exception Start ==========");
            sb.AppendLine(exception.ToString());
            // Possibly useful info inside the Exception (ToString() prints Message and StackTrace):
            // sb.AppendFormat("  ExMessage: {0}\n", exception.Message);
            // sb.AppendFormat("  TargetSite: {0}\n", exception.TargetSite);
            // sb.AppendFormat("  Source: {0}\n", exception.Source);
            // sb.AppendLine("  StackTrace:");
            // sb.AppendLine(exception.StackTrace);
            sb.AppendLine("========== Exception End ==========");
        }
        // CausedBy
        if (causedBy != null)
        {
            sb.AppendLine("========== CausedBy ==========");
            causedBy.WriteToStringBuilder(sb);
        }
    }

    /// <summary>Formats the complete error info (including stack trace/Notes/Exception/CausedBy)</summary>
    public override string ToString()
    {
        // Recursive ToString calls would allocate several StringBuilders, so passing one in saves allocations
        var sb = new StringBuilder();
        WriteToStringBuilder(sb);
        return sb.ToString();
    }

    /// <summary>
    /// This error has been fully resolved.
    /// </summary>
    protected internal override void Reset()
    {
        if (notes.IsValueCreated)
        {
            notes.Value.Clear();
        }
        m_CausedBy = null;
        m_Exception = null;
        m_Message = string.Empty;
        stackTrace.Clear();
        var warped = causedBy;
        while (warped != null)
        {
            warped.Reset();
            warped = warped.causedBy;
        }
    }

    // ReSharper disable ParameterHidesMember
    /// <summary>Re-initializes a pooled instance before it is handed out again</summary>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="causedBy">Underlying error, when there is one</param>
    /// <param name="exception">Underlying exception, when there is one</param>
    /// <param name="callerInfo">Caller info of the frame that creates the error</param>
    /// <remarks>Only called by the pooling machinery and by generated companion classes</remarks>
    protected internal void Init(TKind kind, string message, ErrBase causedBy, Exception exception, CallerInfo callerInfo)
    {
        this.kind = kind;
        m_Message = message;
        m_CausedBy = causedBy;
        m_Exception = exception;
        stackTrace.Add(callerInfo);
    }

    /// <summary>Re-initializes a pooled instance, keeping a whole stack trace</summary>
    /// <param name="kind">Error enum value</param>
    /// <param name="message">Error message</param>
    /// <param name="causedBy">Underlying error, when there is one</param>
    /// <param name="exception">Underlying exception, when there is one</param>
    /// <param name="stackTrace">Stack trace to adopt</param>
    /// <remarks>Only called by the pooling machinery</remarks>
    protected internal void Init(TKind kind, string message, ErrBase causedBy, Exception exception, List<CallerInfo> stackTrace)
    {
        this.kind = kind;
        m_Message = message;
        m_CausedBy = causedBy;
        m_Exception = exception;
        stackTrace.AddRange(stackTrace);
    }
}