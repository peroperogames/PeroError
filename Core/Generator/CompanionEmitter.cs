using System.Text;

namespace PeroTools2.Error.Generator;

/// <summary>Emits a <see cref="CompanionSpec"/> as C# source code</summary>
internal static class CompanionEmitter
{
    private const string runtime_namespace = "global::PeroTools2.Error";
    private const int indent_size = 4;

    /// <summary>Generates the full source of the companion class from <paramref name="spec"/></summary>
    public static string Emit(CompanionSpec spec)
    {
        var sb = new StringBuilder(2048);
        int indent = 0;

        sb.Append("// <auto-generated/>\n");
        sb.Append("// Generated by PeroTools2.PeroError.Generator from [ErrMsg] / [ErrArg] attributes.\n");
        sb.Append("// Changes to the error enum's attributes regenerate this file; do not edit it.\n");
        sb.Append("#pragma warning disable\n");
        sb.Append("#nullable disable\n");
        sb.Append('\n');

        if (spec.namespaceName != null)
        {
            AppendLine(sb, indent, "namespace " + spec.namespaceName);
            AppendLine(sb, indent, "{");
            indent++;
        }

        AppendClassDoc(sb, indent, spec);
        AppendLine(sb, indent,
            "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"" + spec.generatorName + "\", \"" + spec.generatorVersion + "\")]");
        AppendLine(sb, indent, "[global::System.Diagnostics.DebuggerNonUserCodeAttribute]");
        AppendLine(sb, indent,
            spec.accessibility + " sealed class " + spec.className + " : " + runtime_namespace + ".Err<" + spec.enumTypeName + ">");
        AppendLine(sb, indent, "{");

        AppendArgs(sb, indent + 1, spec);
        AppendConstructor(sb, indent + 1, spec);

        AppendLine(sb, indent, "}");

        if (spec.namespaceName != null)
        {
            indent--;
            AppendLine(sb, indent, "}");
        }

        return sb.ToString();
    }

    private static void AppendClassDoc(StringBuilder sb, int indent, CompanionSpec spec)
    {
        string memberRef = spec.enumDisplayName + "." + spec.enumMemberName;
        AppendLine(sb, indent, "/// <summary>");
        AppendLine(sb, indent, "/// <c>" + EscapeXml(memberRef) + "</c> is the companion error class, used to attach data to the error.<br/>");
        AppendLine(sb, indent, "/// Generated by <c>PeroTools2.PeroError.Generator</c> from <c>[ErrMsg]</c> / <c>[ErrArg]</c>.");
        AppendLine(sb, indent, "/// </summary>");
    }

    private static void AppendArgs(StringBuilder sb, int indent, CompanionSpec spec)
    {
        foreach (var arg in spec.args)
        {
            string summary = string.IsNullOrWhiteSpace(arg.comment) ? arg.rawName : arg.comment;
            AppendLine(sb, indent, "/// <summary>" + EscapeXml(summary) + "</summary>");
            AppendLine(sb, indent, "public " + arg.typeName + " " + arg.emittedName + " { get; }");
            sb.Append('\n');
        }
    }

    private static void AppendConstructor(StringBuilder sb, int indent, CompanionSpec spec)
    {
        string memberRef = spec.enumDisplayName + "." + spec.enumMemberName;

        // Documentation
        AppendLine(sb, indent, "/// <summary>Creates the <c>" + EscapeXml(memberRef) + "</c> error.</summary>");
        foreach (var arg in spec.args)
        {
            string summary = string.IsNullOrWhiteSpace(arg.comment) ? arg.rawName : arg.comment;
            AppendLine(sb, indent, "/// <param name=\"" + arg.emittedName + "\">" + EscapeXml(summary) + "</param>");
        }
        AppendLine(sb, indent, "/// <param name=\"msg\">Overrides the default error message; when <c>null</c>, the default message declared by <c>[ErrMsg]</c> is used</param>");
        AppendLine(sb, indent, "/// <param name=\"causedBy\">Underlying error that caused this error</param>");
        AppendLine(sb, indent, "/// <param name=\"ex\">Underlying exception that caused this error</param>");
        AppendLine(sb, indent, "/// <param name=\"callerMemberName\">Do not fill in. Generated by the compiler</param>");
        AppendLine(sb, indent, "/// <param name=\"callerFilePath\">Do not fill in. Generated by the compiler</param>");
        AppendLine(sb, indent, "/// <param name=\"callerLineNumber\">Do not fill in. Generated by the compiler</param>");

        // Parameter list
        AppendLine(sb, indent, "public " + spec.className + "(");
        foreach (var arg in spec.args)
        {
            AppendLine(sb, indent + 1, arg.typeName + " " + arg.emittedName + ",");
        }
        AppendLine(sb, indent + 1, "string msg = null,");
        AppendLine(sb, indent + 1, runtime_namespace + ".ErrBase causedBy = null,");
        AppendLine(sb, indent + 1, "global::System.Exception ex = null,");
        AppendLine(sb, indent + 1, "[global::System.Runtime.CompilerServices.CallerMemberName] string callerMemberName = null,");
        AppendLine(sb, indent + 1, "[global::System.Runtime.CompilerServices.CallerFilePath] string callerFilePath = null,");
        AppendLine(sb, indent + 1, "[global::System.Runtime.CompilerServices.CallerLineNumber] int callerLineNumber = default");
        AppendLine(sb, indent, ") : base(");

        // base call
        AppendLine(sb, indent + 1, spec.enumTypeName + "." + spec.enumMemberName + ",");
        AppendLine(sb, indent + 1, "msg ?? $\"" + spec.interpolatedMessage + "\",");
        AppendLine(sb, indent + 1, "causedBy,");
        AppendLine(sb, indent + 1, "ex,");
        AppendLine(sb, indent + 1, "new " + runtime_namespace + ".CallerInfo(callerMemberName, callerFilePath, callerLineNumber)");
        AppendLine(sb, indent, ")");
        AppendLine(sb, indent, "{");

        foreach (var arg in spec.args)
        {
            AppendLine(sb, indent + 1, "this." + arg.emittedName + " = " + arg.emittedName + ";");
        }

        AppendLine(sb, indent, "}");
    }

    private static void AppendLine(StringBuilder sb, int indent, string text)
    {
        sb.Append(' ', indent * indent_size).Append(text).Append('\n');
    }

    /// <summary>Characters that must be escaped in XML documentation comments</summary>
    private static string EscapeXml(string text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return string.Empty;
        }
        return text
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }
}