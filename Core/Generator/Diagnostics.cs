using Microsoft.CodeAnalysis;

namespace PeroTools2.Error.Generator;

/// <summary>All diagnostics produced by the companion class generator</summary>
internal static class Diagnostics
{
    private const string category = "PeroError.Generator";

    /// <summary>The message template itself is invalid (unmatched braces and so on)</summary>
    public static readonly DiagnosticDescriptor invalidFormatString = new(
        id: "PERR001",
        title: "Invalid error message template",
        messageFormat: "Invalid error message template: {0}",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Braces in the message template must be paired; a literal brace must be written as \"{{\" and \"}}\".");

    /// <summary>The message template references an argument that was never declared</summary>
    public static readonly DiagnosticDescriptor unknownFormatArgument = new(
        id: "PERR002",
        title: "Message template references an undeclared argument",
        messageFormat: "Message template references the undeclared argument '{0}'; add [ErrArg(\"{0}\", typeof(...))]",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>A format item of the message template contains an expression</summary>
    public static readonly DiagnosticDescriptor unsupportedFormatExpression = new(
        id: "PERR003",
        title: "Unsupported message template format item",
        messageFormat: "The message template format item '{0}' is not supported; only {{name}} / {{name,alignment}} / {{name:format}} are allowed",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>Duplicate ErrArg name</summary>
    public static readonly DiagnosticDescriptor duplicateArgumentName = new(
        id: "PERR004",
        title: "Duplicate [ErrArg] name",
        messageFormat: "Duplicate [ErrArg] name '{0}'",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The ErrArg name collides with a parameter of the companion class itself</summary>
    public static readonly DiagnosticDescriptor reservedArgumentName = new(
        id: "PERR005",
        title: "[ErrArg] name conflicts with a built-in parameter",
        messageFormat: "[ErrArg] name '{0}' conflicts with a parameter generated by the companion class; choose another name",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The ErrArg name is not a valid identifier</summary>
    public static readonly DiagnosticDescriptor invalidArgumentName = new(
        id: "PERR006",
        title: "Invalid [ErrArg] name",
        messageFormat: "[ErrArg] name '{0}' is not a valid C# identifier",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The ErrArg type cannot be used</summary>
    public static readonly DiagnosticDescriptor invalidArgumentType = new(
        id: "PERR007",
        title: "Invalid [ErrArg] type",
        messageFormat: "The type of [ErrArg] '{0}' cannot be resolved or cannot be used as a constructor parameter",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The companion class name collides with an existing type</summary>
    public static readonly DiagnosticDescriptor companionNameConflict = new(
        id: "PERR008",
        title: "Companion class name conflicts with an existing type",
        messageFormat: "A type named '{0}' already exists; rename it with [ErrMsg(\"...\", name = \"other name\")] or delete the duplicate",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The same companion class name is generated for more than one enum member</summary>
    public static readonly DiagnosticDescriptor duplicateCompanionName = new(
        id: "PERR015",
        title: "Duplicate generated companion class name",
        messageFormat: "The companion class '{0}' is already generated for '{1}'; give one of them another name with [ErrMsg(\"...\", name = \"other name\")]",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Two error enum members must not generate companion classes with the same name in the same namespace.");

    /// <summary>Companion classes cannot be generated for nested enums</summary>
    public static readonly DiagnosticDescriptor nestedEnumNotSupported = new(
        id: "PERR009",
        title: "Companion classes are not supported for nested enums",
        messageFormat: "Cannot generate a companion class for the error enum '{0}' nested in a type; move it to namespace level",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>The ErrArg has no matching ErrMsg</summary>
    public static readonly DiagnosticDescriptor argumentWithoutMessage = new(
        id: "PERR010",
        title: "[ErrArg] has no effect",
        messageFormat: "[ErrArg] on '{0}' has no effect because no [ErrMsg] is declared",
        category: category,
        defaultSeverity: DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    /// <summary>The ErrMsg is applied to a field that is not an enum member</summary>
    public static readonly DiagnosticDescriptor messageOnNonEnumField = new(
        id: "PERR011",
        title: "[ErrMsg] is only allowed on error enum members",
        messageFormat: "[ErrMsg] is only allowed on error enum members; '{0}' was ignored",
        category: category,
        defaultSeverity: DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    /// <summary>The custom companion class name is invalid</summary>
    public static readonly DiagnosticDescriptor invalidCompanionName = new(
        id: "PERR014",
        title: "Invalid companion class name",
        messageFormat: "Companion class name '{0}' is not a valid C# identifier",
        category: category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);
}